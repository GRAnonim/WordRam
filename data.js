  isValidWord(word) {
    if (!word || word.length < 3) return false;
    const upper = word.toUpperCase();
    const len = upper.length;
    for (const lvl of ["A1", "A2", "B1", "B2", "C1"]) {
      if (this.cefrDictionary[lvl][len] && this.cefrDictionary[lvl][len].includes(upper)) {
        return true;
      }
    }
    return false;
  }
